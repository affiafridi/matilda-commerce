/** A code for the NEXT 30-second step: always newer than the one used at enrolment, and still accepted. */
export const nextCode = (secret: string): string =>
  generateSync({ secret, epoch: Math.floor(Date.now() / 1000) + 30 });

interface Mail {
  to: string;
  template: string;
  text: string;
}

/** The link in the most recent message to `email`, read from the captured mail like a person would. */
export function tokenFromMail(email: string, linkPath: string): string {
  if (!existsSync(OUTBOX)) throw new Error('No mail captured yet');
  const mails = readFileSync(OUTBOX, 'utf8')
    .split('\n')
    .filter(Boolean)
    .map((l) => JSON.parse(l) as Mail)
    .filter((m) => m.to.toLowerCase() === email.toLowerCase());
  for (const mail of mails.reverse()) {
    const match = new RegExp(`${linkPath}\\?token=([A-Za-z0-9_-]+)`).exec(mail.text);
    if (match?.[1]) return match[1];
  }
  throw new Error(`No ${linkPath} link found for ${email}`);
}

export function createSuperAdminLink(email: string, name: string): string {
  const out = execFileSync(
    process.execPath,
    [
      join(API_DIR, 'dist/cli/create-super-admin.js'),
      '--email',
      email,
      '--name',
      name,
      '--force-recovery',
    ],
    {
      cwd: API_DIR,
      encoding: 'utf8',
      env: {
        ...process.env,
        ...loadEnv(),
        NODE_ENV: 'test',
        DATABASE_URL: loadEnv().TEST_DATABASE_URL ?? '',
        MIGRATION_DATABASE_URL: loadEnv().TEST_MIGRATION_DATABASE_URL ?? '',
        ADMIN_BASE_URL: ORIGIN,
      },
    },
  );
  const match = /token=([A-Za-z0-9_-]+)/.exec(out);
  if (!match?.[1]) throw new Error('create-super-admin did not print an invitation link');
  return match[1];
}

function loadEnv(): Record<string, string> {
  const text = readFileSync(join(API_DIR, '.env'), 'utf8');
  const env: Record<string, string> = {};
  for (const line of text.split('\n')) {
    const m = /^([A-Z0-9_]+)=(.*)$/.exec(line.trim());
    if (m?.[1]) env[m[1]] = (m[2] ?? '').replace(/^"|"$/g, '');
  }
  return env;
}

/** Minimal cookie-aware API client used only to prepare fixtures. */
export class ApiSession {
  private cookie = '';
  csrf = '';

  /** Raw value of the session cookie, for building a browser storage state. */
  sessionToken(): string {
    return this.cookie.split('=').slice(1).join('=');
  }

  async call(method: string, path: string, body?: unknown, extra: Record<string, string> = {}) {
    const res = await fetch(`${API}${path}`, {
      method,
      headers: {
        Origin: ORIGIN,
        ...(body !== undefined ? { 'Content-Type': 'application/json' } : {}),
        ...(this.cookie ? { Cookie: this.cookie } : {}),
        ...(this.csrf ? { 'X-CSRF-Token': this.csrf } : {}),
        ...extra,
      },
      ...(body !== undefined ? { body: JSON.stringify(body) } : {}),
    });
    const set = res.headers.getSetCookie();
    const session = set.map((c) => c.split(';')[0]).find((c) => c?.includes('matilda_staff'));
    if (session) this.cookie = session;
    const text = await res.text();
    const json = text ? (JSON.parse(text) as Record<string, unknown>) : {};
    if (!res.ok) throw new Error(`${method} ${path} -> ${res.status} ${text}`);
    return json;
  }

  /** Accept an invitation, sign in and enrol 2FA through the API (what the screens do). */
  async activate(token: string, email: string): Promise<string> {
    await this.call('POST', '/admin/auth/invite/accept', { token, password: password() });
    const login = await this.call('POST', '/admin/auth/login', { email, password: password() });
    this.csrf = login.csrfToken as string;
    const start = await this.call('POST', '/admin/auth/mfa/enroll/start', {});
    const secret = start.secret as string;
    const done = await this.call('POST', '/admin/auth/mfa/enroll/confirm', {
      code: generateSync({ secret }),
    });
    this.csrf = done.csrfToken as string;
    return secret;
  }
}
